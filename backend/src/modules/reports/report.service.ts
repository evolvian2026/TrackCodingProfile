export type ReportFormat = 'xlsx' | 'csv' | 'pdf';

export interface GeneratedReport {
  buffer: Buffer;
  filename: string;
  contentType: string;
}

const CONTENT_TYPES: Record<ReportFormat, string> = {
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  csv: 'text/csv; charset=utf-8',
  pdf: 'application/pdf',
};

const HEADER_FILL: ExcelJS.Fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1E293B' } };

/** "Not published by the platform" must read differently from a real zero. */
const show = (value: number | null | undefined): string | number => (value === null || value === undefined ? 'N/A' : value);

function styleHeader(sheet: ExcelJS.Worksheet) {
  const row = sheet.getRow(1);
  row.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  row.fill = HEADER_FILL;
  row.alignment = { vertical: 'middle' };
  row.height = 20;
  sheet.views = [{ state: 'frozen', ySplit: 1 }];
}

function autoWidth(sheet: ExcelJS.Worksheet, min = 10, max = 44) {
  sheet.columns.forEach((column) => {
    let width = min;
    column.eachCell?.({ includeEmpty: false }, (cell) => {
      width = Math.max(width, String(cell.value ?? '').length + 2);
    });
    column.width = Math.min(max, width);
  });
}

async function workbookToBuffer(workbook: ExcelJS.Workbook, format: 'xlsx' | 'csv'): Promise<Buffer> {
  if (format === 'csv') {
    // CSV holds a single sheet; the first one carries the primary table.
    return Buffer.from(await workbook.csv.writeBuffer({ sheetName: workbook.worksheets[0]?.name }) as ArrayBuffer);
  }
  return Buffer.from(await workbook.xlsx.writeBuffer() as ArrayBuffer);
}

const safeName = (value: string) => value.replace(/[^A-Za-z0-9._-]+/g, '_').slice(0, 60);

