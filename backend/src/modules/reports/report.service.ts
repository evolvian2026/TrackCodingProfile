const INK = '#0F172A';
const MUTED = '#64748B';
const RULE = '#E2E8F0';

function pdfToBuffer(doc: PDFKit.PDFDocument): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    doc.end();
  });
}

function pdfHeading(doc: PDFKit.PDFDocument, text: string) {
  if (doc.y > doc.page.height - 140) doc.addPage();
  doc.moveDown(0.8);
  doc.fillColor(INK).fontSize(13).font('Helvetica-Bold').text(text);
  doc.moveTo(doc.x, doc.y + 3).lineTo(doc.page.width - doc.page.margins.right, doc.y + 3).strokeColor(RULE).stroke();
  doc.moveDown(0.6);
}

function pdfTable(doc: PDFKit.PDFDocument, headers: string[], rows: (string | number)[][], widths: number[]) {
  const left = doc.page.margins.left;
  const drawRow = (cells: (string | number)[], bold: boolean) => {
    if (doc.y > doc.page.height - 70) {
      doc.addPage();
    }
    const y = doc.y;
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(9).fillColor(bold ? INK : '#334155');
    let x = left;
    cells.forEach((cell, i) => {
      doc.text(String(cell), x, y, { width: widths[i]! - 6, ellipsis: true, lineBreak: false });
      x += widths[i]!;
    });
    doc.y = y + 15;
  };

  drawRow(headers, true);
  doc.moveTo(left, doc.y - 3).lineTo(left + widths.reduce((a, b) => a + b, 0), doc.y - 3).strokeColor(RULE).stroke();
  for (const row of rows) drawRow(row, false);
}

/** Horizontal bar chart drawn with primitives — no chart library needed. */
function pdfBars(doc: PDFKit.PDFDocument, entries: { label: string; value: number; color?: string }[], maxWidth = 260) {
  const max = Math.max(1, ...entries.map((e) => e.value));
  const left = doc.page.margins.left;
  for (const entry of entries) {
    if (doc.y > doc.page.height - 70) doc.addPage();
    const y = doc.y;
    doc.font('Helvetica').fontSize(9).fillColor('#334155').text(entry.label, left, y, { width: 130, ellipsis: true, lineBreak: false });
    const width = Math.max(2, (entry.value / max) * maxWidth);
    doc.rect(left + 140, y - 1, width, 9).fill(entry.color ?? '#2563EB');
    doc.fillColor('#334155').font('Helvetica').fontSize(9).text(String(entry.value), left + 145 + maxWidth, y, { lineBreak: false });
    doc.y = y + 15;
  }
}

async function renderStudentPdf(
  student: Awaited<ReturnType<typeof getStudentDetail>>,
  topics: Awaited<ReturnType<typeof getStudentTopics>>,
  contests: Awaited<ReturnType<typeof getStudentContests>>,
  history: Awaited<ReturnType<typeof getStudentHistory>>,
): Promise<Buffer> {
  const doc = new PDFDocument({ size: 'A4', margin: 42, info: { Title: `Student Report — ${student.name}` } });
  const a = student.analytics;

  doc.fillColor(INK).fontSize(20).font('Helvetica-Bold').text(student.name);
  doc
    .fillColor(MUTED)
    .fontSize(10)
    .font('Helvetica')
    .text(
      [`Student ID: ${student.studentId}`, student.branch, student.batch, student.college].filter(Boolean).join('  |  '),
    );
  doc.moveDown(0.3);
  doc.fillColor(MUTED).fontSize(8).text(`Generated ${new Date().toUTCString()}`);

  pdfHeading(doc, 'Competitive Programming Score');
  if (a?.hasData) {
    doc.fillColor(INK).fontSize(28).font('Helvetica-Bold').text(`${a.cpScore} / 100`);
    doc.fillColor(MUTED).fontSize(8).font('Helvetica').text('Generated by this application from public platform data. Not an official platform metric.');
  } else {
    doc.fillColor(MUTED).fontSize(11).font('Helvetica').text('N/A — no platform data has been retrieved for this student yet.');
  }

  pdfHeading(doc, 'Platform Profiles');
  pdfTable(
    doc,
    ['Platform', 'Username', 'Status', 'Solved', 'Rating', 'Contests'],
    student.platforms.map((p) => [
      PLATFORMS[p.platform].label,
      p.username,
      p.status,
      show(p.totalSolved),
      show(p.rating),
      show(p.contestsAttended),
    ]),
    [90, 120, 90, 60, 60, 60],
  );

  pdfHeading(doc, 'Problems by Platform');
  const platformBars = student.platforms
    .filter((p) => p.totalSolved !== null)
    .map((p) => ({ label: PLATFORMS[p.platform].label, value: p.totalSolved!, color: PLATFORMS[p.platform].colors.light }));
  if (platformBars.length > 0) pdfBars(doc, platformBars);
  else doc.fillColor(MUTED).fontSize(10).text('No platform published a solved count for this student.');

  if (a?.difficultyKnown) {
    pdfHeading(doc, 'Difficulty Distribution');
    pdfBars(doc, [
      { label: 'Easy', value: a.easySolved, color: '#16A34A' },
      { label: 'Medium', value: a.mediumSolved, color: '#D97706' },
      { label: 'Hard', value: a.hardSolved, color: '#DC2626' },
      {
        label: 'Unclassified',
        value: Math.max(0, a.totalSolved - a.easySolved - a.mediumSolved - a.hardSolved),
        color: '#94A3B8',
      },
    ]);
  } else if (a?.hasData) {
    pdfHeading(doc, 'Difficulty Distribution');
    doc
      .fillColor(MUTED)
      .fontSize(10)
      .font('Helvetica')
      .text('N/A — none of the platforms with data for this student publish an Easy/Medium/Hard split.');
  }

  pdfHeading(doc, 'Top Topics');
  if (topics.unified.length > 0) {
    pdfBars(doc, topics.unified.slice(0, 12).map((t) => ({ label: t.topic, value: t.problemsSolved })));
  } else {
    doc.fillColor(MUTED).fontSize(10).text('No topic breakdown is publicly available for this student.');
  }

  pdfHeading(doc, 'Skill Matrix');
  if (student.skills.length > 0) {
    pdfTable(
      doc,
      ['Skill', 'Level', 'Problems', 'Platforms'],
      student.skills.slice(0, 18).map((s) => [s.topic, s.level, s.problemsSolved, s.platformCount]),
      [190, 110, 80, 80],
    );
  } else {
    doc.fillColor(MUTED).fontSize(10).text('Not enough topic data to build a skill matrix.');
  }

  pdfHeading(doc, 'Contest Performance');
  doc
    .fillColor('#334155')
    .fontSize(10)
    .font('Helvetica')
    .text(
      `Contests: ${contests.summary.total}   |   Best rank: ${show(contests.summary.bestRank)}   |   Average rank: ${show(contests.summary.averageRank)}`,
    );
  doc.moveDown(0.4);
  if (contests.data.length > 0) {
    pdfTable(
      doc,
      ['Platform', 'Contest', 'Date', 'Rank', 'Change'],
      contests.data.slice(0, 20).map((c) => [
        PLATFORMS[c.platform].label,
        c.name,
        c.date ? c.date.toISOString().slice(0, 10) : 'N/A',
        show(c.rank),
        show(c.ratingChange),
      ]),
      [80, 190, 80, 60, 60],
    );
  } else {
    doc.fillColor(MUTED).fontSize(10).text('No contest history is publicly available for this student.');
  }

  if (history.length > 1) {
    pdfHeading(doc, 'Growth Over Time');
    pdfTable(
      doc,
      ['Date', 'Solved', 'Rating', 'Contests', 'CP Score'],
      history.slice(-15).map((h) => [
        h.date.toISOString().slice(0, 10),
        show(h.totalSolved),
        show(h.rating),
        show(h.contestsAttended),
        show(h.cpScore),
      ]),
      [110, 90, 90, 90, 90],
    );
  }

  return pdfToBuffer(doc);
}

async function renderBatchPdf(
  analytics: Awaited<ReturnType<typeof getBatchAnalytics>>,
  leaderboard: Awaited<ReturnType<typeof getLeaderboard>>['data'],
): Promise<Buffer> {
  const doc = new PDFDocument({ size: 'A4', margin: 42, info: { Title: `Batch Report — ${analytics.batch}` } });

  doc.fillColor(INK).fontSize(20).font('Helvetica-Bold').text(`Batch ${analytics.batch}`);
  doc
    .fillColor(MUTED)
    .fontSize(10)
    .font('Helvetica')
    .text(`${analytics.studentCount} students  |  ${analytics.studentsWithData} with retrieved data`);
  doc.fillColor(MUTED).fontSize(8).text(`Generated ${new Date().toUTCString()}`);

  pdfHeading(doc, 'Batch Statistics');
  pdfTable(
    doc,
    ['Metric', 'Average', 'Median', 'Min', 'Max'],
    Object.entries(analytics.averages).map(([metric, dist]) => [
      metric.replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase()),
      show(dist.average),
      show(dist.median),
      show(dist.min),
      show(dist.max),
    ]),
    [160, 90, 90, 80, 80],
  );

  pdfHeading(doc, 'Highlights');
  const h = analytics.highlights;
  pdfTable(
    doc,
    ['Category', 'Student', 'Value'],
    [
      ['Top CP Score', h.topStudent?.name ?? 'N/A', h.topStudent?.cpScore ?? 'N/A'],
      ['Most Problems Solved', h.mostProblemsSolved?.name ?? 'N/A', h.mostProblemsSolved?.totalSolved ?? 'N/A'],
      ['Highest Rating', h.highestRating?.name ?? 'N/A', h.highestRating?.bestRating ?? 'N/A'],
    ],
    [170, 200, 130],
  );

  pdfHeading(doc, 'Top 10 Students');
  pdfTable(
    doc,
    ['#', 'Student', 'Solved', 'Rating', 'Contests', 'Score'],
    leaderboard.slice(0, 10).map((row) => [
      row.rank,
      row.name,
      row.totalSolved,
      show(row.currentRating),
      row.totalContests,
      row.cpScore,
    ]),
    [30, 190, 70, 70, 70, 70],
  );

  pdfHeading(doc, 'Platform Adoption');
  pdfBars(
    doc,
    analytics.platformAdoption.map((p) => ({ label: p.label, value: p.linked, color: p.color })),
  );

  pdfHeading(doc, 'Strongest Topics');
  pdfBars(doc, analytics.strengths.map((t) => ({ label: t.topic, value: t.problemsSolved })));

  pdfHeading(doc, 'Weakest Topics');
  pdfBars(
    doc,
    analytics.weaknesses.map((t) => ({ label: t.topic, value: t.problemsSolved, color: '#94A3B8' })),
  );

  return pdfToBuffer(doc);
}
