export async function generateBatchReport(batch: string, format: ReportFormat): Promise<GeneratedReport> {
  const analytics = await getBatchAnalytics(batch);
  if (analytics.studentCount === 0) throw notFound(`No students found in batch "${batch}"`);

  const [leaderboard, topics] = await Promise.all([
    getLeaderboard({ batch }, { pageSize: 200 }),
    getTopicAnalytics({ batch }),
  ]);

  const filename = `batch-report-${safeName(batch)}.${format}`;

  if (format === 'pdf') {
    return { buffer: await renderBatchPdf(analytics, leaderboard.data), filename, contentType: CONTENT_TYPES.pdf };
  }

  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Competitive Programming Student Performance Tracker';

  const leaderboardSheet = workbook.addWorksheet('Leaderboard');
  leaderboardSheet.columns = [
    { header: 'Rank', key: 'rank' },
    { header: 'Student ID', key: 'studentId' },
    { header: 'Name', key: 'name' },
    { header: 'College', key: 'college' },
    { header: 'Branch', key: 'branch' },
    { header: 'Problems Solved', key: 'solved' },
    { header: 'Easy', key: 'easy' },
    { header: 'Medium', key: 'medium' },
    { header: 'Hard', key: 'hard' },
    { header: 'Contest Rating', key: 'rating' },
    { header: 'Contests', key: 'contests' },
    { header: 'Topics', key: 'topics' },
    { header: 'CP Score', key: 'score' },
  ];
  leaderboardSheet.addRows(
    leaderboard.data.map((row) => ({
      rank: row.rank,
      studentId: row.studentId,
      name: row.name,
      college: row.college ?? 'N/A',
      branch: row.branch ?? 'N/A',
      solved: row.totalSolved,
      easy: row.difficultyKnown ? row.easySolved : 'N/A',
      medium: row.difficultyKnown ? row.mediumSolved : 'N/A',
      hard: row.difficultyKnown ? row.hardSolved : 'N/A',
      rating: show(row.currentRating),
      contests: row.contestsKnown ? row.totalContests : 'N/A',
      topics: row.topicCount,
      score: row.cpScore,
    })),
  );
  styleHeader(leaderboardSheet);
  autoWidth(leaderboardSheet);

  const statsSheet = workbook.addWorksheet('Batch Statistics');
  statsSheet.columns = [
    { header: 'Metric', key: 'metric' },
    { header: 'Average', key: 'average' },
    { header: 'Median', key: 'median' },
    { header: 'Min', key: 'min' },
    { header: 'Max', key: 'max' },
    { header: 'Students', key: 'count' },
  ];
  for (const [metric, dist] of Object.entries(analytics.averages)) {
    statsSheet.addRow({
      metric,
      average: show(dist.average),
      median: show(dist.median),
      min: show(dist.min),
      max: show(dist.max),
      count: dist.count,
    });
  }
  styleHeader(statsSheet);
  autoWidth(statsSheet);

  const platformSheet = workbook.addWorksheet('Platform Adoption');
  platformSheet.columns = [
    { header: 'Platform', key: 'platform' },
    { header: 'Profiles Linked', key: 'linked' },
    { header: 'Data Available', key: 'available' },
    { header: 'Adoption %', key: 'adoption' },
  ];
  platformSheet.addRows(
    analytics.platformAdoption.map((p) => ({
      platform: p.label,
      linked: p.linked,
      available: p.available,
      adoption: p.adoptionRate,
    })),
  );
  styleHeader(platformSheet);
  autoWidth(platformSheet);

  const topicSheet = workbook.addWorksheet('Topic Analysis');
  topicSheet.columns = [
    { header: 'Topic', key: 'topic' },
    { header: 'Problems Solved', key: 'solved' },
    { header: 'Students', key: 'students' },
    { header: 'Share %', key: 'share' },
  ];
  topicSheet.addRows(
    topics.topics.map((t) => ({ topic: t.topic, solved: t.problemsSolved, students: t.studentCount, share: t.share })),
  );
  styleHeader(topicSheet);
  autoWidth(topicSheet);

  return { buffer: await workbookToBuffer(workbook, format), filename, contentType: CONTENT_TYPES[format] };
}

