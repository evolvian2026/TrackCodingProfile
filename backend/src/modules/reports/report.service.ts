export async function generateLeaderboardExport(
  filters: StudentFilters,
  format: 'xlsx' | 'csv',
  limit = 1000,
): Promise<GeneratedReport> {
  const leaderboard = await getLeaderboard(filters, { pageSize: Math.min(200, limit) });
  const pages = Math.min(Math.ceil(limit / 200), leaderboard.pagination.totalPages);

  const rows = [...leaderboard.data];
  for (let page = 2; page <= pages; page++) {
    const next = await getLeaderboard(filters, { pageSize: 200, page });
    rows.push(...next.data);
  }

  const workbook = new ExcelJS.Workbook();
  const sheet = workbook.addWorksheet('Leaderboard');
  sheet.columns = [
    { header: 'Rank', key: 'rank' },
    { header: 'Student ID', key: 'studentId' },
    { header: 'Name', key: 'name' },
    { header: 'College', key: 'college' },
    { header: 'Batch', key: 'batch' },
    { header: 'Branch', key: 'branch' },
    { header: 'Problems Solved', key: 'solved' },
    { header: 'Contest Rating', key: 'rating' },
    { header: 'Contests', key: 'contests' },
    { header: 'Topic Coverage %', key: 'coverage' },
    { header: 'CP Score', key: 'score' },
  ];
  sheet.addRows(
    rows.slice(0, limit).map((row) => ({
      rank: row.rank,
      studentId: row.studentId,
      name: row.name,
      college: row.college ?? 'N/A',
      batch: row.batch ?? 'N/A',
      branch: row.branch ?? 'N/A',
      solved: row.totalSolved,
      rating: show(row.currentRating),
      contests: row.contestsKnown ? row.totalContests : 'N/A',
      coverage: row.topicsKnown ? row.topicCoverage : 'N/A',
      score: row.cpScore,
    })),
  );
  styleHeader(sheet);
  autoWidth(sheet);

  return {
    buffer: await workbookToBuffer(workbook, format),
    filename: `leaderboard.${format}`,
    contentType: CONTENT_TYPES[format],
  };
}

/** Failed-profile export for the error dashboard. */
export async function generateFailureReport(format: 'xlsx' | 'csv', jobId?: string): Promise<GeneratedReport> {
  const items = await prisma.processingJobItem.findMany({
    where: { status: { in: ['FAILED', 'RATE_LIMITED'] }, ...(jobId ? { jobId } : {}) },
    include: { student: { select: { studentId: true, name: true } }, job: { select: { number: true } } },
    orderBy: { updatedAt: 'desc' },
    take: 10_000,
  });

  const workbook = new ExcelJS.Workbook();
  const sheet = workbook.addWorksheet('Failures');
  sheet.columns = [
    { header: 'Job', key: 'job' },
    { header: 'Student ID', key: 'studentId' },
    { header: 'Student', key: 'name' },
    { header: 'Platform', key: 'platform' },
    { header: 'Status', key: 'status' },
    { header: 'Data Status', key: 'dataStatus' },
    { header: 'Attempts', key: 'attempts' },
    { header: 'Error', key: 'error' },
    { header: 'Last Attempt', key: 'lastAttempt' },
  ];
  sheet.addRows(
    items.map((item) => ({
      job: `#${item.job.number}`,
      studentId: item.student.studentId,
      name: item.student.name,
      platform: PLATFORMS[item.platform].label,
      status: item.status,
      dataStatus: item.dataStatus ?? 'N/A',
      attempts: item.attempts,
      error: item.lastError ?? '',
      lastAttempt: item.finishedAt?.toISOString() ?? '',
    })),
  );
  styleHeader(sheet);
  autoWidth(sheet);

  return {
    buffer: await workbookToBuffer(workbook, format),
    filename: `failed-profiles.${format}`,
    contentType: CONTENT_TYPES[format],
  };
}

