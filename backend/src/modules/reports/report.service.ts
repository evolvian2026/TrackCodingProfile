export async function generateStudentReport(studentId: string, format: ReportFormat): Promise<GeneratedReport> {
  const student = await getStudentDetail(studentId);
  const [topics, contests, ratings, history] = await Promise.all([
    getStudentTopics(student.id),
    getStudentContests(student.id),
    getStudentRatings(student.id),
    getStudentHistory(student.id, undefined, 365),
  ]);

  const filename = `student-report-${safeName(student.studentId)}.${format}`;

  if (format === 'pdf') {
    return {
      buffer: await renderStudentPdf(student, topics, contests, history),
      filename,
      contentType: CONTENT_TYPES.pdf,
    };
  }

  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Competitive Programming Student Performance Tracker';
  workbook.created = new Date();

  // -- Summary --------------------------------------------------------------
  const summary = workbook.addWorksheet('Summary');
  summary.columns = [
    { header: 'Field', key: 'field' },
    { header: 'Value', key: 'value' },
  ];
  const a = student.analytics;
  summary.addRows([
    { field: 'Student ID', value: student.studentId },
    { field: 'Name', value: student.name },
    { field: 'Email', value: student.email ?? 'N/A' },
    { field: 'College', value: student.college ?? 'N/A' },
    { field: 'Batch', value: student.batch ?? 'N/A' },
    { field: 'Branch', value: student.branch ?? 'N/A' },
    { field: 'Section', value: student.section ?? 'N/A' },
    { field: 'Competitive Programming Score (out of 100)', value: a?.hasData ? a.cpScore : 'N/A' },
    { field: 'Total Problems Solved', value: a?.hasData ? a.totalSolved : 'N/A' },
    // Easy/Medium/Hard are only real numbers when a platform published a split.
    { field: 'Easy Solved', value: a?.difficultyKnown ? a.easySolved : 'N/A' },
    { field: 'Medium Solved', value: a?.difficultyKnown ? a.mediumSolved : 'N/A' },
    { field: 'Hard Solved', value: a?.difficultyKnown ? a.hardSolved : 'N/A' },
    { field: 'Contests Participated', value: a?.contestsKnown ? a.totalContests : 'N/A' },
    { field: 'Best Contest Rank', value: show(a?.bestRank) },
    { field: 'Current Rating (best across platforms)', value: show(a?.currentRating) },
    { field: 'Peak Rating', value: show(a?.bestRating) },
    { field: 'Distinct Topics', value: a?.topicsKnown ? a.topicCount : 'N/A' },
    { field: 'Report Generated', value: new Date().toISOString() },
    { field: 'Note', value: 'The CP Score is generated by this application and is not an official platform metric.' },
  ]);
  styleHeader(summary);
  autoWidth(summary);

  // -- Platform profiles ----------------------------------------------------
  const platforms = workbook.addWorksheet('Platforms');
  platforms.columns = [
    { header: 'Platform', key: 'platform' },
    { header: 'Username', key: 'username' },
    { header: 'Profile URL', key: 'url' },
    { header: 'Status', key: 'status' },
    { header: 'Status Detail', key: 'detail' },
    { header: 'Solved', key: 'solved' },
    { header: 'Easy', key: 'easy' },
    { header: 'Medium', key: 'medium' },
    { header: 'Hard', key: 'hard' },
    { header: 'Rating', key: 'rating' },
    { header: 'Max Rating', key: 'maxRating' },
    { header: 'Global Rank', key: 'globalRank' },
    { header: 'Contests', key: 'contests' },
    { header: 'Last Updated', key: 'updated' },
  ];
  for (const p of student.platforms) {
    platforms.addRow({
      platform: PLATFORMS[p.platform].label,
      username: p.username,
      url: p.profileUrl,
      status: p.status,
      detail: p.statusMessage ?? '',
      solved: show(p.totalSolved),
      easy: show(p.easySolved),
      medium: show(p.mediumSolved),
      hard: show(p.hardSolved),
      rating: show(p.rating),
      maxRating: show(p.maxRating),
      globalRank: show(p.globalRank),
      contests: show(p.contestsAttended),
      updated: p.lastSuccessAt?.toISOString() ?? 'Never',
    });
  }
  styleHeader(platforms);
  autoWidth(platforms);

  // -- Topics ---------------------------------------------------------------
  const topicSheet = workbook.addWorksheet('Topics');
  topicSheet.columns = [
    { header: 'Topic', key: 'topic' },
    { header: 'Problems Solved', key: 'solved' },
  ];
  topicSheet.addRows(topics.unified.map((t) => ({ topic: t.topic, solved: t.problemsSolved })));
  styleHeader(topicSheet);
  autoWidth(topicSheet);

  // -- Skill matrix ---------------------------------------------------------
  const skillSheet = workbook.addWorksheet('Skill Matrix');
  skillSheet.columns = [
    { header: 'Skill', key: 'topic' },
    { header: 'Level', key: 'level' },
    { header: 'Score', key: 'score' },
    { header: 'Problems Solved', key: 'solved' },
    { header: 'Platforms', key: 'platforms' },
  ];
  skillSheet.addRows(
    student.skills.map((s) => ({
      topic: s.topic,
      level: s.level,
      score: s.score,
      solved: s.problemsSolved,
      platforms: s.platformCount,
    })),
  );
  styleHeader(skillSheet);
  autoWidth(skillSheet);

  // -- Contests -------------------------------------------------------------
  const contestSheet = workbook.addWorksheet('Contests');
  contestSheet.columns = [
    { header: 'Platform', key: 'platform' },
    { header: 'Contest', key: 'name' },
    { header: 'Date', key: 'date' },
    { header: 'Rank', key: 'rank' },
    { header: 'Rating Before', key: 'before' },
    { header: 'Rating After', key: 'after' },
    { header: 'Change', key: 'change' },
    { header: 'Problems Solved', key: 'solved' },
  ];
  contestSheet.addRows(
    contests.data.map((c) => ({
      platform: PLATFORMS[c.platform].label,
      name: c.name,
      date: c.date ? c.date.toISOString().slice(0, 10) : 'N/A',
      rank: show(c.rank),
      before: show(c.ratingBefore),
      after: show(c.ratingAfter),
      change: show(c.ratingChange),
      solved: show(c.problemsSolved),
    })),
  );
  styleHeader(contestSheet);
  autoWidth(contestSheet);

  // -- Rating history -------------------------------------------------------
  const ratingSheet = workbook.addWorksheet('Rating History');
  ratingSheet.columns = [
    { header: 'Platform', key: 'platform' },
    { header: 'Date', key: 'date' },
    { header: 'Rating', key: 'rating' },
    { header: 'Contest', key: 'contest' },
  ];
  for (const series of ratings.series) {
    for (const point of series.points) {
      ratingSheet.addRow({
        platform: series.label,
        date: point.date.toISOString().slice(0, 10),
        rating: point.rating,
        contest: point.contestName ?? '',
      });
    }
  }
  styleHeader(ratingSheet);
  autoWidth(ratingSheet);

  // -- Growth over time -----------------------------------------------------
  const growth = workbook.addWorksheet('Growth');
  growth.columns = [
    { header: 'Date', key: 'date' },
    { header: 'Problems Solved', key: 'solved' },
    { header: 'Rating', key: 'rating' },
    { header: 'Contests', key: 'contests' },
    { header: 'CP Score', key: 'score' },
  ];
  growth.addRows(
    history.map((h) => ({
      date: h.date.toISOString().slice(0, 10),
      solved: show(h.totalSolved),
      rating: show(h.rating),
      contests: show(h.contestsAttended),
      score: show(h.cpScore),
    })),
  );
  styleHeader(growth);
  autoWidth(growth);

  return { buffer: await workbookToBuffer(workbook, format), filename, contentType: CONTENT_TYPES[format] };
}

